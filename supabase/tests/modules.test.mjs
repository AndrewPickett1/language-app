// Tests for finishing a Learn module (complete_module), against an in-process Postgres (PGlite).
// Run with: npm run test:db
import { PGlite } from '@electric-sql/pglite';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

const migration = (name) => readFileSync(new URL(`../migrations/${name}`, import.meta.url), 'utf8');

const A = '00000000-0000-0000-0000-00000000000a';
const B = '00000000-0000-0000-0000-00000000000b';

// Just enough of Supabase for the migrations: auth.users, auth.uid(), the API roles, the words
// tables as they are on the live project, and stand-ins for the lotto functions.
const Stubs = `
  create role anon nologin;
  create role authenticated nologin;
  create schema auth;
  grant usage on schema auth, public to anon, authenticated;
  create table auth.users (id uuid primary key);
  create function auth.uid() returns uuid language sql stable
    as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  grant execute on function auth.uid() to anon, authenticated;

  create table public.profiles (id uuid primary key references auth.users (id), current_streak smallint default 0, best_streak smallint default 0);
  create table public.language (id bigint primary key, name text not null);
  create table public.words (id bigint primary key, word text not null);
  create table public.user_words (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    user_id uuid not null references auth.users (id),
    word_id bigint references public.words (id)
  );

  create function public.grant_lotto_pull(p_user uuid)
  returns table (granted boolean, current_lotto_pulls integer, max_lotto_pulls integer, next_pull_at timestamptz)
  language sql security definer set search_path = '' as $$ select true, 1, 1, null::timestamptz $$;
  revoke all on function public.grant_lotto_pull(uuid) from public;
  create function public.get_lotto_state()
  returns table (current_lotto_pulls integer, max_lotto_pulls integer, next_pull_at timestamptz)
  language sql security definer set search_path = '' as $$ select 1, 1, null::timestamptz $$;
`;

async function setup() {
  const db = new PGlite();
  await db.exec(Stubs);
  await db.exec(`insert into auth.users values ('${A}'), ('${B}');`);
  await db.exec(migration('20261025212531_create_user_streaks.sql'));
  await db.exec(migration('20261025212740_drop_profiles_streak_columns.sql'));
  await db.exec(migration('20261025213811_daily_streaks.sql'));
  await db.exec(migration('20261025221934_create_modules.sql'));
  await db.exec(migration('20261029235228_module_completion_tracking.sql'));
  await db.exec(migration('20261029235238_complete_module_fix_reward_vars.sql'));
  await db.exec(migration('20261031120000_complete_module_adds_words.sql'));
  await db.exec(`grant all on public.user_words, public.words, public.user_streaks to anon, authenticated;`);
  // Two modules in order: the first teaches words 1–3, the second words 3–4.
  await db.exec(`
    insert into public.language values (1, 'French');
    insert into public.words values (1, 'bonjour'), (2, 'merci'), (3, 'oui'), (4, 'non');
    insert into public.modules (id, language_id, position, title) values (10, 1, 0, 'Hello'), (11, 1, 1, 'Yes and no');
    insert into public.module_words (module_id, word_id, position) values (10, 1, 0), (10, 2, 1), (10, 3, 2), (11, 3, 0), (11, 4, 1);
  `);
  return db;
}

/** Runs `sql` as a signed-in user (or anon when `user` is null), the way PostgREST would. */
async function as(db, user, sql, params) {
  return db.transaction(async (tx) => {
    await tx.exec(`set local role ${user ? 'authenticated' : 'anon'}`);
    await tx.query(`select set_config('request.jwt.claim.sub', $1, true)`, [user ?? '']);
    return tx.query(sql, params);
  });
}

async function complete(db, user, moduleId) {
  const { rows } = await as(db, user, `select * from public.complete_module($1, 90::smallint)`, [moduleId]);
  return rows[0];
}

async function wordIds(db, user) {
  const { rows } = await db.query(`select word_id from public.user_words where user_id = $1 order by id`, [user]);
  return rows.map((r) => Number(r.word_id));
}

test('finishing a module adds its words to the learner\'s words', async () => {
  const db = await setup();
  const done = await complete(db, A, 10);
  assert.equal(done.words_added, 3);
  assert.equal(done.pull_granted, true);
  assert.deepEqual(await wordIds(db, A), [1, 2, 3]);
  assert.deepEqual(await wordIds(db, B), []);
});

test('words the learner already has are not added again', async () => {
  const db = await setup();
  await db.exec(`insert into public.user_words (user_id, word_id) values ('${A}', 2);`);
  assert.equal((await complete(db, A, 10)).words_added, 2);
  assert.deepEqual(await wordIds(db, A), [2, 1, 3]);

  // Word 3 came with the first module, so the second only brings word 4.
  assert.equal((await complete(db, A, 11)).words_added, 1);
  assert.deepEqual(await wordIds(db, A), [2, 1, 3, 4]);
});

test('replaying a module adds nothing new', async () => {
  const db = await setup();
  await complete(db, A, 10);
  const again = await complete(db, A, 10);
  assert.equal(again.words_added, 0);
  assert.equal(again.times_completed, 2);
  assert.deepEqual(await wordIds(db, A), [1, 2, 3]);
});

test('a locked module adds no words', async () => {
  const db = await setup();
  await assert.rejects(complete(db, A, 11), /MODULE_LOCKED/);
  assert.deepEqual(await wordIds(db, A), []);
});
