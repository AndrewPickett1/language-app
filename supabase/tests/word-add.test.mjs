// Tests for the one-word-a-day Add a word migration, against an in-process Postgres (PGlite).
// Run with: npm run test:db
import { PGlite } from '@electric-sql/pglite';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

const migration = (name) => readFileSync(new URL(`../migrations/${name}`, import.meta.url), 'utf8');

const A = '00000000-0000-0000-0000-00000000000a';
const B = '00000000-0000-0000-0000-00000000000b';

// Just enough of Supabase for the migrations: auth.users, auth.uid(), the API roles, and the
// profiles, words and user_words tables as they are on the live project.
const Stubs = `
  create role anon nologin;
  create role authenticated nologin;
  create schema auth;
  grant usage on schema auth, public to anon, authenticated;
  create table auth.users (id uuid primary key);
  create function auth.uid() returns uuid language sql stable
    as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  grant execute on function auth.uid() to anon, authenticated;

  create table public.profiles (
    id uuid primary key references auth.users (id),
    created_at timestamptz not null default now(),
    currently_selected_language bigint,
    current_streak smallint default 0,
    best_streak smallint default 0
  );
  create table public.words (id bigint primary key, word text not null);
  create table public.user_words (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    user_id uuid not null references auth.users (id),
    word_id bigint references public.words (id)
  );
`;

async function setup() {
  const db = new PGlite();
  await db.exec(Stubs);
  await db.exec(`insert into auth.users values ('${A}'), ('${B}');
                 insert into public.profiles (id) values ('${A}');
                 insert into public.words values (1, 'el gato'), (2, 'el perro'), (3, 'la casa');`);
  await db.exec(migration('20261025212531_create_user_streaks.sql'));
  await db.exec(migration('20261025212740_drop_profiles_streak_columns.sql'));
  await db.exec(migration('20261025213811_daily_streaks.sql'));
  // Supabase grants table access to the API roles by default; the migration narrows profiles.
  await db.exec(`grant all on public.profiles, public.user_words, public.words, public.user_streaks to anon, authenticated;`);
  await db.exec(migration('20261027120000_daily_word_add.sql'));
  return db;
}

/** Runs `sql` as a signed-in user (or anon when `user` is null), the way PostgREST would. */
async function as(db, user, sql, params) {
  return db.transaction(async (tx) => {
    await tx.exec(`set local role ${user ? 'authenticated' : 'anon'}`);
    await tx.query(`select set_config('request.jwt.claim.sub', $1, true)`, [user ?? '']);
    return tx.query(sql, params);
  });
}

async function add(db, user, wordId) {
  const { rows } = await as(db, user, `select * from public.add_word($1)`, [wordId]);
  return rows[0].status;
}

async function available(db, user) {
  const { rows } = await as(db, user, `select * from public.get_word_add_status()`);
  return rows[0].available;
}

async function wordIds(db, user) {
  const { rows } = await db.query(`select word_id from public.user_words where user_id = $1 order by id`, [user]);
  return rows.map((r) => Number(r.word_id));
}

test('the first add of the day saves the word and uses up the day', async () => {
  const db = await setup();
  assert.equal(await available(db, A), true);
  assert.equal(await add(db, A, 1), 'added');
  assert.deepEqual(await wordIds(db, A), [1]);
  assert.equal(await available(db, A), false);
});

test('a second add the same day is refused and saves nothing', async () => {
  const db = await setup();
  await add(db, A, 1);
  assert.equal(await add(db, A, 2), 'used');
  assert.deepEqual(await wordIds(db, A), [1]);
});

test('adding works again on the next local day', async () => {
  const db = await setup();
  await add(db, A, 1);
  await db.exec(`update public.profiles set last_word_added_on = last_word_added_on - 1 where id = '${A}'`);
  assert.equal(await available(db, A), true);
  assert.equal(await add(db, A, 2), 'added');
  assert.deepEqual(await wordIds(db, A), [1, 2]);
});

test('a stored day after today (timezone change) still blocks', async () => {
  const db = await setup();
  await add(db, A, 1);
  await db.exec(`update public.profiles set last_word_added_on = last_word_added_on + 1 where id = '${A}'`);
  assert.equal(await available(db, A), false);
  assert.equal(await add(db, A, 2), 'used');
});

test('an owned word or an unknown id does not use up the day', async () => {
  const db = await setup();
  await db.exec(`insert into public.user_words (user_id, word_id) values ('${A}', 3)`);
  assert.equal(await add(db, A, 3), 'owned');
  assert.equal(await add(db, A, 999), 'unknown_word');
  assert.equal(await available(db, A), true);
  assert.equal(await add(db, A, 1), 'added');
});

test('a learner without a profiles row gets one on their first add', async () => {
  const db = await setup();
  assert.equal(await available(db, B), true);
  assert.equal(await add(db, B, 1), 'added');
  assert.equal(await add(db, B, 2), 'used');
});

test("one learner's add doesn't use up another's", async () => {
  const db = await setup();
  await add(db, A, 1);
  assert.equal(await add(db, B, 1), 'added');
});

test('a successful add marks today done on the streak', async () => {
  const db = await setup();
  await add(db, A, 1);
  const { rows } = await as(db, A, `select * from public.get_streak_summary()`);
  assert.equal(rows[0].current_streak, 1);
  assert.equal(rows[0].days.at(-1), 'done');
});

test('a refused add does not count toward the streak', async () => {
  const db = await setup();
  await add(db, A, 999);
  const { rows } = await db.query(`select 1 from public.user_streaks where user_id = $1 and last_active_date is not null`, [A]);
  assert.equal(rows.length, 0);
});

test('signed-in users cannot write last_word_added_on but can still change their language', async () => {
  const db = await setup();
  await assert.rejects(as(db, A, `update public.profiles set last_word_added_on = null where id = '${A}'`), /permission denied/);
  await assert.rejects(as(db, B, `insert into public.profiles (id, last_word_added_on) values ('${B}', '2000-01-01')`), /permission denied/);
  await as(db, A, `update public.profiles set currently_selected_language = 7 where id = '${A}'`);
  await as(db, B, `insert into public.profiles (id, currently_selected_language) values ('${B}', 7)`);
  const { rows } = await db.query(`select count(*)::int as n from public.profiles where currently_selected_language = 7`);
  assert.equal(rows[0].n, 2);
});

test('the functions need a signed-in user', async () => {
  const db = await setup();
  await assert.rejects(as(db, null, `select * from public.add_word(1)`), /permission denied/);
  await assert.rejects(as(db, null, `select * from public.get_word_add_status()`), /permission denied/);
});
