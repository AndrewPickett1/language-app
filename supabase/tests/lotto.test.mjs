// Tests for Lotto pulls (spend_lotto_pull picking the word, and guaranteed-rarity pulls), against an in-process Postgres (PGlite).
// Run with: npm run test:db
import { PGlite } from '@electric-sql/pglite';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

const migration = (name) => readFileSync(new URL(`../migrations/${name}`, import.meta.url), 'utf8');

const A = '00000000-0000-0000-0000-00000000000a';
const B = '00000000-0000-0000-0000-00000000000b';

// Just enough of Supabase for the migration: auth.users, auth.uid(), the API roles, the words tables
// and lotto helpers as they are on the live project, the functions it replaces, and a record_activity
// that logs its calls.
const Stubs = `
  create role anon nologin;
  create role authenticated nologin;
  create schema auth;
  grant usage on schema auth, public to anon, authenticated;
  create table auth.users (id uuid primary key);
  create function auth.uid() returns uuid language sql stable
    as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  grant execute on function auth.uid() to anon, authenticated;

  create type public.rarity as enum ('Common', 'Uncommon', 'Rare', 'Super Rare', 'Ultra Rare');
  create table public.language (id bigint primary key, name text);
  create table public.words (
    id bigint primary key,
    word text not null,
    rarity public.rarity not null,
    language_id bigint references public.language (id),
    lotto_eligible boolean not null default true
  );
  create table public.user_words (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    user_id uuid not null references auth.users (id),
    word_id bigint references public.words (id)
  );

  create table public.lotto_state (
    user_id uuid primary key references auth.users (id) on delete cascade,
    current_lotto_pulls integer not null default 1 check (current_lotto_pulls >= 0),
    max_lotto_pulls integer not null default 1 check (max_lotto_pulls >= 1),
    recharge_start_time timestamptz not null default now(),
    updated_at timestamptz not null default now()
  );
  create function public.lotto_recharge_interval() returns interval language sql immutable as $$ select interval '3 hours' $$;
  create function public.lotto_calc(p_current integer, p_start timestamptz, p_max integer, p_recharge interval, p_now timestamptz, out cur integer, out start_time timestamptz)
  language plpgsql immutable as $$
  declare regen int;
  begin
    regen := greatest(0, floor(extract(epoch from p_now - p_start) / extract(epoch from p_recharge))::int);
    cur := least(p_max, p_current + regen);
    if cur >= p_max then start_time := p_now; else start_time := p_start + regen * p_recharge; end if;
  end;
  $$;

  create table public.activity_log (user_id uuid);
  create function public.record_activity(p_user uuid) returns void language sql security definer set search_path = ''
    as $$ insert into public.activity_log values (p_user) $$;

  create function public.get_lotto_state()
  returns table (current_lotto_pulls integer, max_lotto_pulls integer, next_pull_at timestamptz, server_now timestamptz)
  language sql security definer set search_path = '' as $$ select 1, 1, null::timestamptz, now() $$;
  create function public.spend_lotto_pull()
  returns table (current_lotto_pulls integer, max_lotto_pulls integer, next_pull_at timestamptz, server_now timestamptz, word_id uuid)
  language sql security definer set search_path = '' as $$ select 0, 1, now(), now(), null::uuid $$;
`;

async function setup() {
  const db = new PGlite();
  await db.exec(Stubs);
  await db.exec(`insert into auth.users values ('${A}'), ('${B}');`);
  await db.exec(migration('20261111120000_lotto_guarantees.sql'));
  // Supabase grants table access to the API roles by default; RLS is what limits it.
  await db.exec(`grant all on public.user_words, public.words, public.lotto_state to anon, authenticated;`);
  // Spanish has every rarity but Ultra Rare, plus a word that can't be pulled. French has no words.
  await db.exec(`
    insert into public.language values (1, 'Spanish'), (2, 'French');
    insert into public.words (id, word, rarity, language_id, lotto_eligible) values
      (1, 'el gato', 'Common', 1, true), (2, 'la casa', 'Common', 1, true),
      (3, 'el perro', 'Uncommon', 1, true), (4, 'el cielo', 'Rare', 1, true),
      (5, 'la mariposa', 'Super Rare', 1, true), (6, 'el', 'Common', 1, false);
  `);
  return db;
}

/** Runs `sql` as a signed-in user (or anon when `user` is null), the way PostgREST would. */
async function as(db, user, sql, params) {
  return db.transaction(async (tx) => {
    await tx.exec(`set local role ${user ? 'authenticated' : 'anon'}`);
    await tx.query(`select set_config('request.jwt.claim.sub', $1, true)`, [user ?? '']);
    return tx.query(sql, params);
  });
}

async function spend(db, user, language = 'spanish') {
  const { rows } = await as(db, user, `select * from public.spend_lotto_pull($1)`, [language]);
  return rows[0];
}

async function setPulls(db, user, n) {
  await db.query(
    `insert into public.lotto_state (user_id, current_lotto_pulls, max_lotto_pulls) values ($1, $2, 10)
     on conflict (user_id) do update set current_lotto_pulls = $2, max_lotto_pulls = 10, recharge_start_time = now()`,
    [user, n]
  );
}

async function grant(db, user, rarity, source = 'test') {
  await db.query(`select public.grant_lotto_guarantee($1, $2::public.rarity, $3)`, [user, rarity, source]);
}

async function wordIds(db, user) {
  const { rows } = await db.query(`select word_id from public.user_words where user_id = $1 order by id`, [user]);
  return rows.map((r) => Number(r.word_id));
}

async function rarityOf(db, wordId) {
  const { rows } = await db.query(`select rarity from public.words where id = $1`, [wordId]);
  return rows[0].rarity;
}

async function state(db, user) {
  const { rows } = await as(db, user, `select * from public.get_lotto_state()`);
  return rows[0];
}

// ---- Picking the word ----

test('a spend picks an eligible word in the language and saves it', async () => {
  const db = await setup();
  await setPulls(db, A, 1);
  const r = await spend(db, A);
  const id = Number(r.word_id);
  assert.ok([1, 2, 3, 4, 5].includes(id));
  assert.equal(r.is_new, true);
  assert.equal(r.current_lotto_pulls, 0);
  assert.equal(r.guarantee_used, null);
  assert.deepEqual(await wordIds(db, A), [id]);
  const { rows } = await db.query(`select count(*)::int n from public.activity_log where user_id = $1`, [A]);
  assert.equal(rows[0].n, 1);
});

test('new words come first, then repeats once every word is owned', async () => {
  const db = await setup();
  await setPulls(db, A, 7);
  const seen = [];
  for (let i = 0; i < 5; i++) {
    const r = await spend(db, A);
    assert.equal(r.is_new, true);
    seen.push(Number(r.word_id));
  }
  assert.deepEqual([...seen].sort(), [1, 2, 3, 4, 5]);
  const repeat = await spend(db, A);
  assert.equal(repeat.is_new, false);
  // A repeat isn't saved twice.
  assert.equal((await wordIds(db, A)).length, 5);
});

test('a language with no words spends nothing', async () => {
  const db = await setup();
  await setPulls(db, A, 1);
  await assert.rejects(spend(db, A, 'French'), /NO_WORDS/);
  await assert.rejects(spend(db, A, 'Klingon'), /UNKNOWN_LANGUAGE/);
  assert.equal((await state(db, A)).current_lotto_pulls, 1);
  assert.deepEqual(await wordIds(db, A), []);
});

test('no pulls spends nothing and keeps the guarantee', async () => {
  const db = await setup();
  await setPulls(db, A, 0);
  await grant(db, A, 'Rare');
  await assert.rejects(spend(db, A), /NO_PULLS/);
  assert.equal((await state(db, A)).guaranteed_rarity, 'Rare');
  assert.deepEqual(await wordIds(db, A), []);
});

// ---- Guarantees ----

test('a guarantee forces its rarity and is used up once', async () => {
  const db = await setup();
  await setPulls(db, A, 2);
  await grant(db, A, 'Super Rare');
  assert.equal((await state(db, A)).guaranteed_rarity, 'Super Rare');

  const r = await spend(db, A);
  assert.equal(Number(r.word_id), 5);
  assert.equal(r.guarantee_used, 'Super Rare');
  assert.equal(r.guaranteed_rarity, null);
  assert.equal((await state(db, A)).guaranteed_rarity, null);

  const { rows } = await db.query(`select used_at, word_id from public.lotto_guarantees where user_id = $1`, [A]);
  assert.ok(rows[0].used_at);
  assert.equal(Number(rows[0].word_id), 5);

  assert.equal((await spend(db, A)).guarantee_used, null);
});

test('the highest guarantee is used first', async () => {
  const db = await setup();
  await setPulls(db, A, 2);
  await grant(db, A, 'Uncommon');
  await grant(db, A, 'Rare');
  const first = await spend(db, A);
  assert.equal(first.guarantee_used, 'Rare');
  assert.equal(Number(first.word_id), 4);
  assert.equal(first.guaranteed_rarity, 'Uncommon');
  const second = await spend(db, A);
  assert.equal(second.guarantee_used, 'Uncommon');
  assert.equal(Number(second.word_id), 3);
});

test('a guaranteed rarity with no words falls back to the nearest one', async () => {
  const db = await setup();
  await setPulls(db, A, 1);
  // Spanish has no Ultra Rare words, so Super Rare is the nearest.
  await grant(db, A, 'Ultra Rare');
  const r = await spend(db, A);
  assert.equal(r.guarantee_used, 'Ultra Rare');
  assert.equal(await rarityOf(db, r.word_id), 'Super Rare');
});

test('a guarantee only affects its own learner', async () => {
  const db = await setup();
  await grant(db, A, 'Super Rare');
  assert.equal((await state(db, B)).guaranteed_rarity, null);
  const { rows } = await as(db, B, `select * from public.lotto_guarantees`);
  assert.equal(rows.length, 0);
  assert.equal((await as(db, A, `select * from public.lotto_guarantees`)).rows.length, 1);
});

// ---- Grants ----

test('clients cannot grant or write guarantees, or pick words themselves', async () => {
  const db = await setup();
  await assert.rejects(as(db, A, `select public.grant_lotto_guarantee($1, 'Ultra Rare', 'cheat')`, [A]), /permission denied/);
  await assert.rejects(as(db, A, `insert into public.lotto_guarantees (user_id, rarity, source) values ($1, 'Ultra Rare', 'cheat')`, [A]), /permission denied/);
  await grant(db, A, 'Rare');
  await assert.rejects(as(db, A, `update public.lotto_guarantees set rarity = 'Ultra Rare'`), /permission denied/);
  await assert.rejects(as(db, A, `delete from public.lotto_guarantees`), /permission denied/);
  await assert.rejects(as(db, A, `select public.pick_lotto_word($1, 1, 'Ultra Rare')`, [A]), /permission denied/);
  await assert.rejects(as(db, null, `select * from public.spend_lotto_pull('Spanish')`), /permission denied/);
});
