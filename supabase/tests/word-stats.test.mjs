// Tests for the per-word answer stats (record_word_results), against an in-process Postgres (PGlite).
// Run with: npm run test:db
import { PGlite } from '@electric-sql/pglite';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

const migration = (name) => readFileSync(new URL(`../migrations/${name}`, import.meta.url), 'utf8');

const A = '00000000-0000-0000-0000-00000000000a';
const B = '00000000-0000-0000-0000-00000000000b';

// Just enough of Supabase for the migrations: auth.users, auth.uid(), the API roles, and the words and
// user_words tables as they are on the live project.
const Stubs = `
  create role anon nologin;
  create role authenticated nologin;
  create schema auth;
  grant usage on schema auth, public to anon, authenticated;
  create table auth.users (id uuid primary key);
  create function auth.uid() returns uuid language sql stable
    as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  grant execute on function auth.uid() to anon, authenticated;

  create table public.words (id bigint primary key, word text not null);
  create table public.user_words (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    user_id uuid not null references auth.users (id),
    word_id bigint references public.words (id)
  );
`;

async function setup() {
  const db = new PGlite();
  await db.exec(Stubs);
  await db.exec(`insert into auth.users values ('${A}'), ('${B}');
                 insert into public.words values (1, 'el gato'), (2, 'el perro'), (3, 'la casa');
                 insert into public.user_words (user_id, word_id) values ('${A}', 1), ('${A}', 2), ('${B}', 1);`);
  // Supabase grants table access to the API roles by default; the migration narrows user_words.
  await db.exec(`grant all on public.user_words, public.words to anon, authenticated;`);
  await db.exec(migration('20261102003120_add_answer_stats_to_user_words.sql'));
  await db.exec(migration('20261102120000_record_word_results.sql'));
  return db;
}

/** Runs `sql` as a signed-in user (or anon when `user` is null), the way PostgREST would. */
async function as(db, user, sql, params) {
  return db.transaction(async (tx) => {
    await tx.exec(`set local role ${user ? 'authenticated' : 'anon'}`);
    await tx.query(`select set_config('request.jwt.claim.sub', $1, true)`, [user ?? '']);
    return tx.query(sql, params);
  });
}

const record = (db, user, results) => as(db, user, `select public.record_word_results($1::jsonb)`, [JSON.stringify(results)]);

async function stats(db, user, wordId) {
  const { rows } = await db.query(
    `select times_seen, times_correct, correct_streak, last_seen_at from public.user_words where user_id = $1 and word_id = $2`,
    [user, wordId]
  );
  return rows[0];
}

test('a new word starts with no stats', async () => {
  const db = await setup();
  assert.deepEqual(await stats(db, A, 1), { times_seen: 0, times_correct: 0, correct_streak: 0, last_seen_at: null });
});

test('right answers count as seen and correct and grow the streak, and a wrong one resets it', async () => {
  const db = await setup();
  await record(db, A, [{ word_id: 1, correct: true }, { word_id: 1, correct: true }]);
  let s = await stats(db, A, 1);
  assert.equal(s.times_seen, 2);
  assert.equal(s.times_correct, 2);
  assert.equal(s.correct_streak, 2);
  assert.ok(s.last_seen_at instanceof Date);

  await record(db, A, [{ word_id: 1, correct: false }, { word_id: 1, correct: true }]);
  s = await stats(db, A, 1);
  assert.equal(s.times_seen, 4);
  assert.equal(s.times_correct, 3);
  assert.equal(s.correct_streak, 1);
});

test('a word shown without a question counts as seen and leaves the streak alone', async () => {
  const db = await setup();
  await record(db, A, [{ word_id: 2, correct: true }, { word_id: 2, correct: null }, { word_id: 2 }]);
  const s = await stats(db, A, 2);
  assert.equal(s.times_seen, 3);
  assert.equal(s.times_correct, 1);
  assert.equal(s.correct_streak, 1);
  assert.ok(s.last_seen_at);
});

test("only the learner's own words change, and unowned words are skipped", async () => {
  const db = await setup();
  await record(db, A, [{ word_id: 1, correct: true }, { word_id: 3, correct: true }]);
  assert.equal((await stats(db, B, 1)).times_seen, 0);
  const { rows } = await db.query(`select count(*)::int as n from public.user_words where word_id = 3`);
  assert.equal(rows[0].n, 0);
});

test('anon and bad input are refused', async () => {
  const db = await setup();
  await assert.rejects(record(db, null, [{ word_id: 1, correct: true }]), /permission denied|NOT_AUTHENTICATED/);
  await assert.rejects(as(db, A, `select public.record_word_results('{}'::jsonb)`), /INVALID_RESULTS/);
  await assert.rejects(record(db, A, Array.from({ length: 201 }, () => ({ word_id: 1, correct: true }))), /TOO_MANY_RESULTS/);
});

test('the client can insert a word but not its stats, and cannot update them', async () => {
  const db = await setup();
  await as(db, A, `insert into public.user_words (user_id, word_id) values ($1, 3)`, [A]);
  await assert.rejects(
    as(db, A, `insert into public.user_words (user_id, word_id, times_seen, times_correct) values ($1, 2, 99, 99)`, [A]),
    /permission denied/
  );
  await assert.rejects(as(db, A, `update public.user_words set times_correct = 0 where user_id = $1`, [A]), /permission denied/);
});
