// Tests for what Study picks words by: last_missed_on (record_word_results) and the added_days_ago and
// missed_days_ago that get_word_progress returns, against an in-process Postgres (PGlite).
// Run with: npm run test:db
import { PGlite } from '@electric-sql/pglite';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

const migration = (name) => readFileSync(new URL(`../migrations/${name}`, import.meta.url), 'utf8');

const A = '00000000-0000-0000-0000-00000000000a';
const B = '00000000-0000-0000-0000-00000000000b';

// Just enough of Supabase and the rest of the schema for the migrations. user_local_date reads the learner's
// timezone like the real one; the Lotto grants are no-ops, since no answer here masters a word.
const Stubs = `
  create role anon nologin;
  create role authenticated nologin;
  create schema auth;
  grant usage on schema auth, public to anon, authenticated;
  create table auth.users (id uuid primary key);
  create function auth.uid() returns uuid language sql stable
    as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  grant execute on function auth.uid() to anon, authenticated;

  create type public.rarity as enum ('Common', 'Rare');
  create type public.word_type as enum ('Noun', 'Verb');
  create table public.words (
    id bigint primary key, word text not null, meaning text, rarity public.rarity default 'Common',
    word_type public.word_type default 'Noun', gender text, language_id bigint default 1);
  create table public.user_words (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    user_id uuid not null references auth.users (id),
    word_id bigint references public.words (id)
  );
  create table public.user_streaks (user_id uuid primary key, timezone text not null);

  create function public.user_local_date(p_user uuid) returns date language sql stable security definer set search_path = ''
    as $$ select (now() at time zone coalesce((select s.timezone from public.user_streaks s where s.user_id = p_user), 'UTC'))::date $$;
  revoke all on function public.user_local_date(uuid) from public, anon, authenticated;
  create function public.grant_lotto_pull(p_user uuid) returns table (granted boolean) language sql
    as $$ select false $$;
  create function public.grant_lotto_guarantee(p_user uuid, p_rarity public.rarity, p_source text) returns void language sql
    as $$ select $$;
`;

async function setup() {
  const db = new PGlite();
  await db.exec(Stubs);
  await db.exec(`insert into auth.users values ('${A}'), ('${B}');
                 insert into public.words (id, word) values (1, 'el gato'), (2, 'el perro'), (3, 'la casa');
                 insert into public.user_words (user_id, word_id) values ('${A}', 1), ('${A}', 2), ('${B}', 1);`);
  await db.exec(`grant all on public.user_words, public.words to anon, authenticated;`);
  for (const name of [
    '20261102003120_add_answer_stats_to_user_words.sql',
    '20261102003725_record_word_results.sql',
    '20261117023928_word_mastery_columns.sql',
    '20261117024148_word_mastery_functions.sql',
    '20261122203948_word_last_missed.sql',
  ]) {
    await db.exec(migration(name));
  }
  return db;
}

/** Runs `sql` as a signed-in user (or anon when `user` is null), the way PostgREST would. */
async function as(db, user, sql, params) {
  return db.transaction(async (tx) => {
    await tx.exec(`set local role ${user ? 'authenticated' : 'anon'}`);
    await tx.query(`select set_config('request.jwt.claim.sub', $1, true)`, [user ?? '']);
    return tx.query(sql, params);
  });
}

const record = (db, user, results) => as(db, user, `select public.record_word_results($1::jsonb)`, [JSON.stringify(results)]);

async function progress(db, user) {
  const { rows } = await as(db, user, `select word_id::int, added_days_ago, missed_days_ago from public.get_word_progress()`);
  return Object.fromEntries(rows.map((r) => [r.word_id, r]));
}

test('a new word was added today and never missed', async () => {
  const db = await setup();
  assert.deepEqual((await progress(db, A))[1], { word_id: 1, added_days_ago: 0, missed_days_ago: null });
});

test('a wrong answer stamps today as the last miss, and a right one keeps it', async () => {
  const db = await setup();
  await record(db, A, [{ word_id: 1, correct: false }]);
  assert.equal((await progress(db, A))[1].missed_days_ago, 0);

  await db.exec(`update public.user_words set last_missed_on = last_missed_on - 2 where word_id = 1`);
  await record(db, A, [{ word_id: 1, correct: true }]);
  assert.equal((await progress(db, A))[1].missed_days_ago, 2);

  await record(db, A, [{ word_id: 2, correct: true }]);
  assert.equal((await progress(db, A))[2].missed_days_ago, null);
});

test("days ago count the learner's local days", async () => {
  const db = await setup();
  await db.exec(`update public.user_words set created_at = now() - interval '3 days' where user_id = '${A}' and word_id = 1`);
  assert.equal((await progress(db, A))[1].added_days_ago, 3);

  // A minute before the learner's midnight was yesterday for them, whatever day it was in UTC.
  await db.exec(`insert into public.user_streaks values ('${A}', 'Pacific/Kiritimati')`);
  await db.exec(`update public.user_words
                    set created_at = ((now() at time zone 'Pacific/Kiritimati')::date::timestamp at time zone 'Pacific/Kiritimati') - interval '1 minute'
                  where user_id = '${A}' and word_id = 2`);
  assert.equal((await progress(db, A))[1].added_days_ago, 3);
  assert.equal((await progress(db, A))[2].added_days_ago, 1);
});

test('only the learner sees their own words, and anon is refused', async () => {
  const db = await setup();
  assert.deepEqual(Object.keys(await progress(db, B)), ['1']);
  await assert.rejects(progress(db, null), /permission denied/);
});

test('the client cannot write last_missed_on', async () => {
  const db = await setup();
  await assert.rejects(as(db, A, `update public.user_words set last_missed_on = current_date where user_id = $1`, [A]), /permission denied/);
});
