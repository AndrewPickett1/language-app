-- Story mode modules: an ordered list of lessons per language, each teaching a set of words.
-- Content tables like words: anyone can read them, and only the service role writes them.
create table public.modules (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  language_id bigint not null references public.language(id) on update cascade on delete cascade,
  position smallint not null check (position >= 0),
  title text not null,
  description text,
  unique (language_id, position)
);

comment on table public.modules is 'Story mode modules, in order within each language.';
comment on column public.modules.position is 'Order of the module within its language, from 0.';

create table public.module_words (
  module_id bigint not null references public.modules(id) on update cascade on delete cascade,
  word_id bigint not null references public.words(id) on update cascade on delete cascade,
  position smallint not null default 0 check (position >= 0),
  created_at timestamptz not null default now(),
  primary key (module_id, word_id)
);

comment on table public.module_words is 'The words each story mode module teaches.';
comment on column public.module_words.position is 'Order of the word within its module.';

create index module_words_word_id_idx on public.module_words (word_id);

alter table public.modules enable row level security;
alter table public.module_words enable row level security;

create policy "modules: read all" on public.modules
  for select to anon, authenticated
  using (true);

create policy "module_words: read all" on public.module_words
  for select to anon, authenticated
  using (true);
