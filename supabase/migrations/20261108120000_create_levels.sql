-- Levels: each language's modules are grouped into numbered levels, and every module rolls up to one.
-- Content table like modules: anyone can read it, and only the service role writes it.
create table public.levels (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  language_id bigint not null references public.language(id) on update cascade on delete cascade,
  number smallint not null check (number >= 1),
  title text not null,
  description text,
  unique (language_id, number)
);

comment on table public.levels is 'Numbered levels within each language. Every module belongs to one.';
comment on column public.levels.number is 'Order of the level within its language, from 1.';

alter table public.levels enable row level security;

create policy "levels: read all" on public.levels
  for select to anon, authenticated
  using (true);

-- French Level 1, which all of French's existing modules belong to.
insert into public.levels (language_id, number, title)
select l.id, 1, 'Level 1'
  from public.language l
 where l.name = 'French'
on conflict (language_id, number) do nothing;

alter table public.modules
  add column level_id bigint references public.levels(id) on update cascade on delete restrict;

comment on column public.modules.level_id is 'The level this module rolls up to.';

create index modules_level_id_idx on public.modules (level_id);

update public.modules m
   set level_id = lv.id
  from public.levels lv
 where lv.language_id = m.language_id and lv.number = m.unit and m.level_id is null;

alter table public.modules alter column level_id set not null;
