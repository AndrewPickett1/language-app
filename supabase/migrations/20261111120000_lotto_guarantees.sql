-- Guaranteed-rarity pulls, and the server picking every Lotto word.
--
-- A guarantee upgrades the learner's next pull: it still spends a pull, but the word comes from the
-- guaranteed rarity. Guarantees are granted only by other server functions (grant_lotto_guarantee),
-- and spend_lotto_pull uses the highest unused one. The spend now also picks the word and saves it to
-- user_words in the same transaction, so a pull is never spent without its word being kept.

create table public.lotto_guarantees (
  id         bigint generated by default as identity primary key,
  user_id    uuid        not null references auth.users(id) on delete cascade,
  rarity     public.rarity not null,
  -- What earned it, e.g. 'level' or 'streak'. Free text so new triggers don't need a migration here.
  source     text        not null,
  granted_at timestamptz not null default now(),
  used_at    timestamptz,
  -- The word the guaranteed pull gave.
  word_id    bigint      references public.words(id) on delete set null
);

comment on table public.lotto_guarantees is 'Guaranteed-rarity pulls. Server-only: granted by grant_lotto_guarantee(), used by spend_lotto_pull().';

create index lotto_guarantees_unused_idx on public.lotto_guarantees (user_id) where used_at is null;

alter table public.lotto_guarantees enable row level security;

create policy "lotto_guarantees: read own" on public.lotto_guarantees
  for select using ((select auth.uid()) = user_id);

revoke all on public.lotto_guarantees from anon, authenticated;
grant select on public.lotto_guarantees to authenticated;

-- How likely each rarity is to come out of a capsule. Keep in step with RarityInfo[r].weight in src/data/rarity.ts.
create function public.lotto_rarity_weight(p_rarity public.rarity)
returns integer
language sql
immutable
set search_path to ''
as $$
  select case p_rarity
    when 'Common' then 45
    when 'Uncommon' then 28
    when 'Rare' then 15
    when 'Super Rare' then 9
    else 3
  end;
$$;

-- Picks a Lotto word for p_user from a language's lotto_eligible words, weighted by rarity, preferring
-- words they don't have yet. With p_rarity, only words of that rarity; if the language has none, the
-- nearest rarity that has some (higher first). Null when the language has no eligible words at all.
create function public.pick_lotto_word(p_user uuid, p_language_id bigint, p_rarity public.rarity default null)
returns bigint
language plpgsql
volatile
security definer
set search_path to ''
as $$
declare
  tier   public.rarity := p_rarity;
  tiers  public.rarity[] := enum_range(null::public.rarity);
  picked bigint;
begin
  if tier is not null and not exists (
    select 1 from public.words w where w.language_id = p_language_id and w.lotto_eligible and w.rarity = tier
  ) then
    select w.rarity into tier
      from public.words w
     where w.language_id = p_language_id and w.lotto_eligible
     group by w.rarity
     order by abs(array_position(tiers, w.rarity) - array_position(tiers, p_rarity)), w.rarity desc
     limit 1;
  end if;

  -- Owned words sort last, so they only come up once every word is owned. Within each group, a weighted
  -- random pick: the smallest -ln(u)/weight wins with probability weight / total.
  select w.id into picked
    from public.words w
   where w.language_id = p_language_id
     and w.lotto_eligible
     and (tier is null or w.rarity = tier)
   order by exists (select 1 from public.user_words uw where uw.user_id = p_user and uw.word_id = w.id),
            -ln(1 - random()) / public.lotto_rarity_weight(w.rarity)
   limit 1;

  return picked;
end;
$$;

-- Gives p_user a guaranteed pull of p_rarity. For other server functions only: never callable by clients.
create function public.grant_lotto_guarantee(p_user uuid, p_rarity public.rarity, p_source text)
returns bigint
language plpgsql
security definer
set search_path to ''
as $$
declare
  gid bigint;
begin
  if p_user is null then raise exception 'USER_REQUIRED'; end if;
  if p_rarity is null then raise exception 'RARITY_REQUIRED'; end if;

  insert into public.lotto_guarantees (user_id, rarity, source)
  values (p_user, p_rarity, coalesce(nullif(trim(p_source), ''), 'unknown'))
  returning id into gid;

  return gid;
end;
$$;

-- The return types change, so both are dropped and created again.
drop function public.get_lotto_state();
drop function public.spend_lotto_pull();

-- Same as before, plus guaranteed_rarity: the highest unused guarantee, or null.
create function public.get_lotto_state()
returns table (current_lotto_pulls integer, max_lotto_pulls integer, next_pull_at timestamptz, server_now timestamptz, guaranteed_rarity public.rarity)
language plpgsql
stable
security definer
set search_path to ''
as $$
declare
  uid uuid := auth.uid();
  r   interval := public.lotto_recharge_interval();
  s   public.lotto_state%rowtype;
  c   record;
begin
  if uid is null then raise exception 'NOT_AUTHENTICATED'; end if;

  select * into s from public.lotto_state ls where ls.user_id = uid;
  if not found then   -- defensive: user missed the trigger and backfill
    s.current_lotto_pulls := 1; s.max_lotto_pulls := 1; s.recharge_start_time := now();
  end if;

  select * into c from public.lotto_calc(
    s.current_lotto_pulls, s.recharge_start_time, s.max_lotto_pulls, r, now());

  return query select
    c.cur,
    s.max_lotto_pulls,
    case when c.cur >= s.max_lotto_pulls then null::timestamptz else c.start_time + r end,
    now(),
    (select max(lg.rarity) from public.lotto_guarantees lg where lg.user_id = uid and lg.used_at is null);
end;
$$;

-- Spends one pull and gives the learner a word from p_language (matched like the app's deck query,
-- case-insensitively on language.name). Uses the highest unused guarantee, if any. Returns the word,
-- whether it's new to them, the rarity guarantee used (guarantee_used) and the next one (guaranteed_rarity).
create function public.spend_lotto_pull(p_language text)
returns table (
  current_lotto_pulls integer,
  max_lotto_pulls     integer,
  next_pull_at        timestamptz,
  server_now          timestamptz,
  word_id             bigint,
  is_new              boolean,
  guarantee_used      public.rarity,
  guaranteed_rarity   public.rarity
)
language plpgsql
security definer
set search_path to ''
as $$
declare
  uid    uuid := auth.uid();
  r      interval := public.lotto_recharge_interval();
  s      public.lotto_state%rowtype;
  c      record;
  lang   bigint;
  g      public.lotto_guarantees%rowtype;
  picked bigint;
  fresh  boolean;
begin
  if uid is null then raise exception 'NOT_AUTHENTICATED'; end if;

  select l.id into lang from public.language l where l.name ilike p_language order by l.id limit 1;
  if lang is null then raise exception 'UNKNOWN_LANGUAGE'; end if;

  insert into public.lotto_state (user_id) values (uid) on conflict (user_id) do nothing;
  -- Locking the learner's row also keeps two spends from both using the same guarantee or adding the same word.
  select * into s from public.lotto_state ls where ls.user_id = uid for update;

  select * into c from public.lotto_calc(
    s.current_lotto_pulls, s.recharge_start_time, s.max_lotto_pulls, r, now());

  if c.cur < 1 then
    raise exception 'NO_PULLS' using detail = (c.start_time + r)::text;
  end if;

  select * into g
    from public.lotto_guarantees lg
   where lg.user_id = uid and lg.used_at is null
   order by lg.rarity desc, lg.granted_at, lg.id
   limit 1;

  picked := public.pick_lotto_word(uid, lang, g.rarity);
  if picked is null then raise exception 'NO_WORDS'; end if;

  -- user_words has no unique key, so check before adding.
  fresh := not exists (select 1 from public.user_words uw where uw.user_id = uid and uw.word_id = picked);
  if fresh then
    insert into public.user_words (user_id, word_id) values (uid, picked);
  end if;

  if g.id is not null then
    update public.lotto_guarantees lg set used_at = now(), word_id = picked where lg.id = g.id;
  end if;

  update public.lotto_state ls
     set current_lotto_pulls = c.cur - 1,
         recharge_start_time = c.start_time,
         updated_at          = now()
   where ls.user_id = uid;

  -- Only reached once the pull is spent; NO_PULLS and NO_WORDS above count nothing.
  perform public.record_activity(uid);

  return query select
    c.cur - 1,
    s.max_lotto_pulls,
    c.start_time + r,      -- after spending we're below max, so a timer is always running
    now(),
    picked,
    fresh,
    g.rarity,
    (select max(lg.rarity) from public.lotto_guarantees lg where lg.user_id = uid and lg.used_at is null);
end;
$$;

